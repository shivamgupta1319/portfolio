function section(id, title, intro, body) {
  return `
    <section id="${id}" aria-labelledby="${id}-h">
      <div class="sec-head">
        <h2 id="${id}-h">${esc(title)}</h2>
        ${intro ? `<p>${esc(intro)}</p>` : ""}
      </div>
      ${body}
    </section>`;
}

